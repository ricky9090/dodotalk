package org.dodotalk.core;

import java.io.ByteArrayOutputStream;
import java.io.DataOutputStream;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Builds minimal, deterministic Squeak 2.2 images for interpreter tests.
 * <p>
 * This is a test-side writer. It deliberately does not reuse
 * {@link SqueakImage#save} or production header planning: the production
 * reader is the system under test. All values written here are declared
 * explicitly; the generated bytes are never committed.
 * <p>
 * The images contain no Squeak source, changes file, font, or asset. They are
 * small object graphs serialised according to the public Squeak 2.2 object
 * memory layout.
 */
final class SyntheticImageBuilder {

    enum Variant {
        ARITH,
        SEND,
        BENCH
    }

    static final int DEFAULT_BENCH_REPETITIONS = 1_000;
    static final int MAX_BENCH_REPETITIONS = 2_000_000;

    private static final int IMAGE_VERSION = 6502;
    private static final int HEADER_SIZE = 64;
    private static final int OLD_BASE_ADDR = 0x1000_0000;
    private static final int SPL_SLOTS = 64;

    private static final int SPL_NIL = 0;
    private static final int SPL_FALSE = 1;
    private static final int SPL_TRUE = 2;
    private static final int SPL_SCHEDULER_ASSOCIATION = 3;
    private static final int SPL_CLASS_INTEGER = 5;
    private static final int SPL_CLASS_ARRAY = 7;
    private static final int SPL_CLASS_FLOAT = 9;
    private static final int SPL_CLASS_METHOD_CONTEXT = 10;
    private static final int SPL_CLASS_COMPILED_METHOD = 16;
    private static final int SPL_SELECTOR_DOES_NOT_UNDERSTAND = 20;
    private static final int SPL_SELECTOR_CANNOT_RETURN = 21;
    private static final int SPL_SPECIAL_SELECTORS = 23;
    private static final int SPL_SELECTOR_MUST_BE_BOOLEAN = 25;
    private static final int SPL_CLASS_PROCESS = 27;
    private static final int SPL_COMPACT_CLASSES = 28;
    private static final int SPL_SELECTOR_CANNOT_INTERPRET = 34;

    private static final int PUSH_CONSTANT_ONE = 118;
    private static final int PUSH_CONSTANT_TWO = 119;
    private static final int PRIM_ADD = 176;
    private static final int POP_STACK = 135;
    private static final int RETURN_TOP_FROM_METHOD = 124;
    private static final int UNIMPLEMENTED_BYTECODE = 126;

    private SyntheticImageBuilder() {
    }

    static byte[] build(Variant variant) {
        if (variant == Variant.BENCH) {
            return buildBench(DEFAULT_BENCH_REPETITIONS);
        }
        return buildImage(variant, 0);
    }

    static byte[] buildBench(int repetitions) {
        if (repetitions <= 0) {
            throw new IllegalArgumentException("bench repetitions must be positive: " + repetitions);
        }
        if (repetitions > MAX_BENCH_REPETITIONS) {
            throw new IllegalArgumentException("bench repetitions exceed the limit: " + repetitions);
        }
        return buildImage(Variant.BENCH, repetitions);
    }

    static Path writeToTempFile(Variant variant, Path directory) throws IOException {
        Path file = Files.createTempFile(directory, "synthetic-", ".image");
        Files.write(file, build(variant));
        return file;
    }

    private static byte[] buildImage(Variant variant, int repetitions) {
        Builder b = new Builder();
        addBaseObjects(b);

        int topLiteralCount = 0;
        switch (variant) {
            case ARITH -> {
                byte[] topBytes = {
                        PUSH_CONSTANT_ONE, PUSH_CONSTANT_ONE, (byte) PRIM_ADD,
                        RETURN_TOP_FROM_METHOD
                };
                b.add("methodTop", "ClassCompiledMethod", byteFormat(12, topBytes.length),
                        compiledMethodWords(topBytes));
            }
            case SEND -> {
                symbol(b, "symFoo", "foo", 0);
                b.add("methodFoo", "ClassCompiledMethod", byteFormat(12, 2),
                        compiledMethodWords(new byte[] {PUSH_CONSTANT_TWO, RETURN_TOP_FROM_METHOD}));
                b.add("methodArray", "ClassArray", 2, "methodFoo");
                b.add("methodDict", "ClassObject", 2, "nil", "methodArray", "symFoo");
                b.add("ClassFoo", "ClassObject", 1,
                        "nil", "methodDict", small(classFormat(7, 1)),
                        "nil", "nil", "nil", "nil");
                b.add("receiver", "ClassFoo", 1,
                        "nil", "nil", "nil", "nil", "nil", "nil", "nil");
                byte[] topBytes = {33, (byte) 208, RETURN_TOP_FROM_METHOD};
                topLiteralCount = 2;
                b.add("methodTop", "ClassCompiledMethod", byteFormat(12, topBytes.length),
                        compiledMethodWords(topBytes, topLiteralCount, 0, 0, "symFoo", "receiver"));
            }
            case BENCH -> {
                byte[] topBytes = new byte[(repetitions * 4) + 1];
                int at = 0;
                for (int i = 0; i < repetitions; i++) {
                    topBytes[at++] = (byte) PUSH_CONSTANT_ONE;
                    topBytes[at++] = (byte) PUSH_CONSTANT_ONE;
                    topBytes[at++] = (byte) PRIM_ADD;
                    topBytes[at++] = (byte) POP_STACK;
                }
                topBytes[at] = (byte) RETURN_TOP_FROM_METHOD;
                b.add("methodTop", "ClassCompiledMethod", byteFormat(12, topBytes.length),
                        compiledMethodWords(topBytes));
            }
        }

        byte[] haltBytes = {(byte) UNIMPLEMENTED_BYTECODE};
        b.add("methodHalt", "ClassCompiledMethod", byteFormat(12, haltBytes.length),
                compiledMethodWords(haltBytes));

        b.add("contextTop", "ClassMethodContext", 3,
                contextWords("contextHalt", instructionPointer(topLiteralCount), "methodTop"));
        b.add("contextHalt", "ClassMethodContext", 3,
                contextWords("nil", instructionPointer(0), "methodHalt"));
        b.add("process", "ClassProcess", 1,
                "nil", "contextTop", small(0), "nil", "nil");
        b.add("scheduler", "ClassObject", 1,
                "nil", "process", "nil", "nil", "nil", "nil", "nil");
        b.add("schedulerAssociation", "ClassObject", 1,
                "nil", "scheduler", "nil", "nil", "nil", "nil", "nil");
        b.add("specialObjectsArray", "ClassArray", 2, specialObjectSlots());

        return b.build();
    }

    private static void addBaseObjects(Builder b) {
        b.add("ClassObject", "ClassObject", 1,
                "nil", "nil", small(classFormat(7, 1)), "nil", "nil", "nil", "nil");
        classObject(b, "ClassInteger", 0, 1);
        classObject(b, "ClassArray", 0, 2);
        classObject(b, "ClassFloat", 0, 6);
        classObject(b, "ClassMethodContext", 6, 3);
        classObject(b, "ClassCompiledMethod", 0, 12);
        classObject(b, "ClassProcess", 5, 1);
        classObject(b, "ClassSymbol", 0, 8);

        b.add("nil", "ClassObject", 0);
        b.add("false", "ClassObject", 0);
        b.add("true", "ClassObject", 0);

        symbol(b, "symCannotInterpret", "cannotInterpret", 0);
        symbol(b, "symCannotReturn", "cannotReturn:", 0);
        symbol(b, "symDoesNotUnderstand", "doesNotUnderstand:", 0);
        symbol(b, "symMustBeBoolean", "mustBeBoolean", 0);

        b.add("specialSelectors", "ClassArray", 2);
        List<Object> compact = new ArrayList<>(Collections.nCopies(31, "nil"));
        compact.set(0, "ClassInteger");
        compact.set(1, "ClassArray");
        compact.set(2, "ClassFloat");
        compact.set(3, "ClassMethodContext");
        compact.set(4, "ClassCompiledMethod");
        compact.set(5, "ClassProcess");
        compact.set(6, "ClassSymbol");
        compact.set(7, "ClassObject");
        b.add("compactClasses", "ClassArray", 2, compact.toArray());
    }

    private static void classObject(Builder b, String name, int instSize, int format) {
        b.add(name, "ClassObject", 1,
                "nil", "nil", small(classFormat(instSize, format)),
                "nil", "nil", "nil", "nil");
    }

    private static void symbol(Builder b, String name, String text, int hash) {
        byte[] raw = text.getBytes(java.nio.charset.StandardCharsets.US_ASCII);
        b.add(name, "ClassSymbol", byteFormat(8, raw.length), hash,
                words(packedBytes(raw)));
    }

    private static Object[] words(int[] values) {
        Object[] result = new Object[values.length];
        for (int i = 0; i < values.length; i++) {
            result[i] = values[i];
        }
        return result;
    }

    private static Object[] contextWords(String sender, int instructionPointer,
                                         String method) {
        Object[] words = new Object[23];
        Arrays.fill(words, "nil");
        words[0] = sender;
        words[1] = instructionPointer;
        words[2] = small(0);
        words[3] = method;
        words[4] = "nil";
        words[5] = "nil";
        return words;
    }

    private static Object[] specialObjectSlots() {
        Object[] slots = new Object[SPL_SLOTS];
        Arrays.fill(slots, "nil");
        slots[SPL_NIL] = "nil";
        slots[SPL_FALSE] = "false";
        slots[SPL_TRUE] = "true";
        slots[SPL_SCHEDULER_ASSOCIATION] = "schedulerAssociation";
        slots[SPL_CLASS_INTEGER] = "ClassInteger";
        slots[SPL_CLASS_ARRAY] = "ClassArray";
        slots[SPL_CLASS_FLOAT] = "ClassFloat";
        slots[SPL_CLASS_METHOD_CONTEXT] = "ClassMethodContext";
        slots[SPL_CLASS_COMPILED_METHOD] = "ClassCompiledMethod";
        slots[SPL_SELECTOR_DOES_NOT_UNDERSTAND] = "symDoesNotUnderstand";
        slots[SPL_SELECTOR_CANNOT_RETURN] = "symCannotReturn";
        slots[SPL_SPECIAL_SELECTORS] = "specialSelectors";
        slots[SPL_SELECTOR_MUST_BE_BOOLEAN] = "symMustBeBoolean";
        slots[SPL_CLASS_PROCESS] = "ClassProcess";
        slots[SPL_COMPACT_CLASSES] = "compactClasses";
        slots[SPL_SELECTOR_CANNOT_INTERPRET] = "symCannotInterpret";
        return slots;
    }

    private static int instructionPointer(int numLits) {
        return small(((numLits + 1) * 4) + 1);
    }

    private static int small(int value) {
        return (value << 1) | 1;
    }

    private static int classFormat(int instSize, int format) {
        return ((instSize + 1) << 1) | (format << 7);
    }

    private static int byteFormat(int base, int byteCount) {
        int padding = (4 - (byteCount & 3)) & 3;
        return base | padding;
    }

    private static int[] packedBytes(byte[] values) {
        int[] words = new int[(values.length + 3) / 4];
        for (int i = 0; i < values.length; i++) {
            words[i >> 2] |= (values[i] & 0xFF) << (8 * (3 - (i & 3)));
        }
        return words;
    }

    private static int methodHeader(int numLits, int numArgs, int tempCount, int primIndex,
                                    boolean largeFrame) {
        int header = (primIndex & 0x1FF)
                | ((numLits & 0xFF) << 9)
                | ((tempCount & 0x3F) << 18)
                | ((numArgs & 0xF) << 24);
        if (largeFrame) {
            header |= 0x20000;
        }
        return header;
    }

    private static Object[] compiledMethodWords(byte[] bytecodes) {
        return compiledMethodWords(bytecodes, 0, 0, 0);
    }

    private static Object[] compiledMethodWords(byte[] bytecodes, int numLits, int numArgs,
                                                int tempCount, Object... literals) {
        int rawHeader = (methodHeader(numLits, numArgs, tempCount, 0, false) << 1) | 1;
        Object[] words = new Object[1 + literals.length + ((bytecodes.length + 3) / 4)];
        words[0] = rawHeader;
        System.arraycopy(literals, 0, words, 1, literals.length);
        int[] packed = packedBytes(bytecodes);
        for (int i = 0; i < packed.length; i++) {
            words[1 + literals.length + i] = packed[i];
        }
        return words;
    }

    private static final class ImageObject {
        final String name;
        final String className;
        final int format;
        final int hash;
        final List<Object> data;
        int offset;
        int oop;

        ImageObject(String name, String className, int format, int hash, List<Object> data) {
            this.name = name;
            this.className = className;
            this.format = format;
            this.hash = hash;
            this.data = data;
        }
    }

    private static final class Builder {
        private final List<ImageObject> objects = new ArrayList<>();
        private final Map<String, ImageObject> byName = new LinkedHashMap<>();
        private int endOfMemory;

        ImageObject add(String name, String className, int format, int hash, Object... data) {
            if (byName.containsKey(name)) {
                throw new IllegalStateException("duplicate synthetic object: " + name);
            }
            ImageObject object = new ImageObject(name, className, format, hash,
                    new ArrayList<>(Arrays.asList(data)));
            objects.add(object);
            byName.put(name, object);
            return object;
        }

        ImageObject add(String name, String className, int format, Object... data) {
            return add(name, className, format, 0, data);
        }

        byte[] build() {
            layout();
            ByteArrayOutputStream bytes = new ByteArrayOutputStream();
            try (DataOutputStream out = new DataOutputStream(bytes)) {
                out.writeInt(IMAGE_VERSION);
                out.writeInt(HEADER_SIZE);
                out.writeInt(endOfMemory);
                out.writeInt(OLD_BASE_ADDR);
                out.writeInt(byName.get("specialObjectsArray").oop);
                out.writeInt(0);
                out.writeInt((640 << 16) | 480);
                out.writeInt(0);
                out.writeInt(0);
                for (int i = 9 * 4; i < HEADER_SIZE; i++) {
                    out.writeByte(0);
                }
                for (ImageObject object : objects) {
                    out.writeInt(((object.data.size() + 1) << 2));
                    out.writeInt(word(object.className));
                    out.writeInt((object.hash << 17) | (object.format << 8));
                    for (Object value : object.data) {
                        out.writeInt(word(value));
                    }
                }
            } catch (IOException failure) {
                throw new UncheckedIOException(failure);
            }
            byte[] result = bytes.toByteArray();
            if (result.length != HEADER_SIZE + endOfMemory) {
                throw new IllegalStateException("synthetic image size mismatch: "
                        + result.length + " != " + (HEADER_SIZE + endOfMemory));
            }
            return result;
        }

        private void layout() {
            int offset = 0;
            for (ImageObject object : objects) {
                object.offset = offset;
                object.oop = OLD_BASE_ADDR + offset + 8;
                offset += (3 + object.data.size()) * 4;
            }
            endOfMemory = offset;
        }

        private int word(Object value) {
            if (value instanceof String name) {
                ImageObject target = byName.get(name);
                if (target == null) {
                    throw new IllegalStateException("unknown synthetic object reference: " + name);
                }
                return target.oop;
            }
            if (value instanceof Integer raw) {
                return raw;
            }
            throw new IllegalStateException("unsupported synthetic word: " + value);
        }
    }
}
